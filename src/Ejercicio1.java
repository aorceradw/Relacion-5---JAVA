/*Escribe la declaración para cada una de las variables y asígnales un valor inicial en la propia
declaración de variable. */
public class Ejercicio1{
    public static void main(String[] args){
        //a) Variables enteras: p, q

        int p = 5;
        int q = 18;

        System.out.println("El valor de p es: " + p);
        System.out.println("El valor de q es: " + q);

        //b) Variables de tipo float: x, y,z
        float x = 3.14f;
        float y = 2.71f;
        float z = 1.41f;

        System.out.println("El valor de x es: " + x);
        System.out.println("El valor de y es: " + y);
        System.out.println("El valor de z es: " + z);

        //c) Variables carácter: a, b, c
        char a = 'A';
        char b = 'B';
        char c = 'C';

        System.out.println("El valor de a es: " + a);
        System.out.println("El valor de b es: " + b);
        System.out.println("El valor de c es: " + c);

        //d) Variables double: raiz1, raiz2
        double raiz1 = 2.2;
        double raiz2 = 3.12;

        System.out.println("El valor de raiz1 es: " + raiz1);
        System.out.println("El valor de raiz2 es: " + raiz2);

        //e) Variable entera larga: contador f) Variable entera corta: indicador
        long contador = 1000000000L;
        short indicador = 32000;

        System.out.println("El valor de contador es: " + contador);
        System.out.println("El valor de indicador es: " + indicador);
        
        //g) Variable entera: indice h) Variables double: precio, precioFinal

        int indice = 103;
        double precio = 34.99;
        double precioFinal = 24.99; 

        System.out.println("El valor de indice es: " + indice);
        System.out.println("El valor de precio es: " + precio);
        System.out.println("El valor de precioFinal es: " + precioFinal);
        //i) Variables carácter: car1, car2 j) Variable tipo byte: valor

        char car1 = 'X';
        char car2 = 'Y';
        byte valor = 127;

        System.out.println("El valor de car1 es: " + car1);
        System.out.println("El valor de car2 es: " + car2);
        System.out.println("El valor de valor es: " + valor);

       // k) Variables lógicas: primero, ultimo
        boolean primero = true;
        boolean ultimo = false;

        System.out.println("El valor de primero es: " + primero);
        System.out.println("El valor de ultimo es: " + ultimo);

        // l) Variable de tipo cadena de caracteres: nombre
        String nombre = "Angela";
        System.out.println("El valor de nombre es: " + nombre);
    }
}